/**
 * Interface translations.
 *
 * One flat table per language, keyed by dotted strings so a key is greppable
 * across the whole project. No build step and no fetch: the tables ship in this
 * module, which the page already loads, so switching language costs nothing and
 * never leaves a half-translated screen behind.
 *
 * Three rules the tables follow:
 *
 * - Each language carries its own quotation marks around file names, because
 *   « … », “ … ”, „ … “ and 「 … 」 are not interchangeable.
 * - `{name}` placeholders are filled at call time; a value written as an object
 *   of forms is a plural picked by `Intl.PluralRules`, so no language has to
 *   fall back on the "page(s)" trick. Which forms a language needs is its own
 *   business: `other` alone for Chinese, Japanese and Indonesian, `one`/`other`
 *   for the Western languages and Hindi, `one`/`few`/`many`/`other` for Russian.
 * - Anything the model reads rather than the user (the caption announcing an
 *   attachment) is translated too: the model answers in the language it is
 *   spoken to.
 */

