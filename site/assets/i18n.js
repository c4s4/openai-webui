let language = pickInitialLanguage();

/**
 * The language to start in: the remembered choice first, then the browser's
 * preference list in order, then English. `navigator.languages` holds tags such
 * as `fr-CA`, so only the primary subtag is compared.
 */
function pickInitialLanguage() {
  const stored = recall(STORAGE_KEY);
  if (stored && MESSAGES[stored]) return stored;

  for (const tag of navigator.languages ?? [navigator.language ?? ""]) {
    const code = String(tag).toLowerCase().split("-")[0];
    if (MESSAGES[code]) return code;
  }
  return FALLBACK;
}

export function getLanguage() {
  return language;
}

/** No-op for an unknown code, so a stale stored value cannot blank the interface. */
export function setLanguage(code) {
  if (!MESSAGES[code]) return;
  language = code;
  remember(STORAGE_KEY, code);
  document.documentElement.lang = code;
  applyTranslations();
}

/**
 * Translates `key`, filling `{name}` placeholders from `params`. A missing key
 * falls back to English and, failing that, to the key itself: a translation
 * mistake then shows up as a visible key rather than as an empty label.
 */
export function t(key, params = {}) {
  const entry = MESSAGES[language]?.[key] ?? MESSAGES[FALLBACK][key];
  if (entry === undefined) return key;

  const template = typeof entry === "string" ? entry : selectPlural(entry, params.count);
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : ""));
}

function selectPlural(forms, count) {
  const category = new Intl.PluralRules(language).select(Number(count) || 0);
  return forms[category] ?? forms.other;
}

/** Numbers in the local convention: 12.5 in English, 12,5 in French. */
export function formatNumber(value) {
  return value.toLocaleString(language, { maximumFractionDigits: 1 });
}

/**
 * Applies the table to the markup, driven by four attributes rather than by a
 * list of elements held in JavaScript: `data-i18n` (text), `data-i18n-title`,
 * `data-i18n-aria` and `data-i18n-placeholder`. The same pass therefore also
 * re-translates the buttons created for messages already on screen, since it
 * walks the whole document. `root` itself is included, so a single element can
 * be refreshed after its keys change.
 */
export function applyTranslations(root = document) {
  const targets = [
    ["data-i18n", (node, value) => (node.textContent = value)],
    ["data-i18n-title", (node, value) => (node.title = value)],
    ["data-i18n-aria", (node, value) => node.setAttribute("aria-label", value)],
    ["data-i18n-placeholder", (node, value) => (node.placeholder = value)],
  ];

  for (const [attribute, apply] of targets) {
    for (const node of [root, ...root.querySelectorAll(`[${attribute}]`)]) {
      const key = node.getAttribute?.(attribute);
      if (key) apply(node, t(key));
    }
  }
}
